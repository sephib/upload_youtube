@app.cell
def regions_table(mo, widget_ui):
    """Display regions as an editable table."""
    if not hasattr(widget_ui, "value"):
        mo.stop(True)

    regions = widget_ui.value.get("regions", [])

    table_data = [
        {
            "ID": r["id"],
            "Label": r.get("label", ""),
            "Start (s)": round(r["start"], 3),
            "End (s)": round(r["end"], 3),
            "Duration (s)": round(r["end"] - r["start"], 3),
        }
        for r in regions
    ]

    table = mo.ui.table(
        table_data,
        selection="single",
        label="Audio Regions",
    )

    table
    return (table,)


@app.cell
def sync_table_to_waveform(mo, table, widget):
    """When user clicks a table row, seek to that region."""
    if not table.value:
        mo.stop(True)

    selected_row = table.value[0]
    region_id = selected_row["ID"]

    # Find the region and seek to its start time
    for region in widget.regions:
        if region["id"] == region_id:
            widget.current_time = region["start"]
            widget.selected_region_id = region_id
            break

    mo.md(f"**Selected:** {selected_row['Label']} ({region_id})")
    return


