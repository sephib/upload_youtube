@app.cell
def export_button_handler(mo, widget_ui, export_btn):
    """Handle export button clicks and display results."""
    import json

    if export_btn.value:
        _regions = widget_ui.value.get("regions", [])
        json_output = json.dumps(_regions, indent=2)

        result = mo.vstack(
            [
                mo.callout(
                    "✅ Regions exported! Copy the JSON below:",
                    kind="success",
                ),
                mo.ui.code_editor(value=json_output, language="json", disabled=True),
            ]
        )
    else:
        result = export_btn

    result
    return


