@app.cell(hide_code=True)
def generate_synthetic_audio(np, io):
    """Generate multi-pitch synthetic audio sample.

    Generated by Claude Sonnet 4.5
    """
    sample_rate = 44100
    duration = 5.0

    # Three musical notes: A4 (440Hz), C5 (523Hz), E5 (659Hz)
    segment_duration = duration / 3

    # Generate three segments with different frequencies
    t1 = np.linspace(0, segment_duration, int(sample_rate * segment_duration))
    segment1 = np.sin(2 * np.pi * 440 * t1)  # A4

    t2 = np.linspace(0, segment_duration, int(sample_rate * segment_duration))
    segment2 = np.sin(2 * np.pi * 523 * t2)  # C5

    t3 = np.linspace(0, segment_duration, int(sample_rate * segment_duration))
    segment3 = np.sin(2 * np.pi * 659 * t3)  # E5

    # Concatenate segments
    audio = np.concatenate([segment1, segment2, segment3])

    # Normalize and convert to 16-bit PCM
    audio = audio / np.max(np.abs(audio)) * 0.8
    audio_int16 = (audio * 32767).astype(np.int16)

    # Create WAV file in memory
    wav_buffer = io.BytesIO()
    data_size = len(audio_int16) * 2
    byte_rate = sample_rate * 2

    wav_buffer.write(b"RIFF")
    wav_buffer.write((36 + data_size).to_bytes(4, "little"))
    wav_buffer.write(b"WAVE")
    wav_buffer.write(b"fmt ")
    wav_buffer.write((16).to_bytes(4, "little"))  # fmt chunk size
    wav_buffer.write((1).to_bytes(2, "little"))  # PCM format
    wav_buffer.write((1).to_bytes(2, "little"))  # Mono
    wav_buffer.write(sample_rate.to_bytes(4, "little"))
    wav_buffer.write(byte_rate.to_bytes(4, "little"))
    wav_buffer.write((2).to_bytes(2, "little"))  # Block align
    wav_buffer.write((16).to_bytes(2, "little"))  # Bits per sample
    wav_buffer.write(b"data")
    wav_buffer.write(data_size.to_bytes(4, "little"))
    wav_buffer.write(audio_int16.tobytes())

    audio_bytes = wav_buffer.getvalue()
    audio_path = "/tmp/wavesurfer_demo_audio.wav"

    # Write to temporary file for wavesurfer to read
    with open(audio_path, "wb") as _f:
        _f.write(audio_bytes)

    return (audio_path,)


@app.cell(hide_code=True)
def load_audio_source(audio_path, file_picker, mo):
    """Load audio from upload or use generated sample."""
    if file_picker.value is not None and len(file_picker.value) > 0:
        # Use uploaded file - save to temp file
        uploaded_audio = file_picker.value[0].contents
        audio_name = file_picker.value[0].name
        temp_path = f"/tmp/{audio_name}"
        with open(temp_path, "wb") as _f:
            _f.write(uploaded_audio)

        source_info = mo.callout(
            f"✅ Using uploaded file: **{audio_name}**", kind="success"
        )
        final_audio_path = temp_path
    else:
        # Use generated sample
        source_info = mo.callout(
            "🎹 Using generated sample (3 musical pitches: A4 → C5 → E5)",
            kind="info",
        )
        final_audio_path = audio_path

    source_info
    return (final_audio_path,)


