@app.cell
def load_audio(file_picker, mo, repo_root):
    """Load audio from uploaded file or fallback to sample."""
    audio_bytes = None
    audio_name = "No audio loaded"
    status_message = ""

    if file_picker.value is not None and len(file_picker.value) > 0:
        audio_bytes = file_picker.value[0].contents
        audio_name = file_picker.value[0].name
        status_message = f"✅ **Loaded:** {audio_name}"
    else:
        # Try to find a sample audio file in the project
        sample_paths = [
            repo_root / "demos" / "assets" / "sample.mp3",  # Demo sample file
            repo_root / "data" / "audio" / "sample.mp3",
            repo_root / "data" / "cache" / "audio_segments",
        ]

        for sample_path in sample_paths:
            if sample_path.exists():
                if sample_path.is_file():
                    # Direct file path
                    with open(sample_path, "rb") as f:
                        audio_bytes = f.read()
                    audio_name = sample_path.name
                    status_message = f"📁 **Using sample:** {audio_name}"
                    break
                else:
                    # Directory - find first MP3
                    audio_files = list(sample_path.glob("*.mp3"))
                    if audio_files:
                        sample_file = audio_files[0]
                        with open(sample_file, "rb") as f:
                            audio_bytes = f.read()
                        audio_name = sample_file.name
                        status_message = f"📁 **Using sample:** {audio_name}"
                        break

        if audio_bytes is None:
            status_message = """
⚠️ **No audio file loaded**

Please upload an audio file above or the sample file will be downloaded.
"""

    mo.md(status_message)
    return (audio_bytes,)


