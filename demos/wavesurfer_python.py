@app.cell
def get_current_regions(regions_data, table_data, update_btn):
    """Get current regions from table (reactive to button click)."""
    # Trigger reactive update when button is clicked
    _ = update_btn.value

    # Use table data if modified, otherwise use initial data
    if table_data.value is not None and len(table_data.value) > 0:
        current_regions = table_data.value
    else:
        current_regions = regions_data

    return (current_regions,)


@app.cell(hide_code=True)
def display_waveform(current_regions, final_audio_path, mo, play, speed_selector):
    """Display waveform with alignments."""
    mo.md("## 🎵 Waveform Visualization")

    # Convert regions to alignment format for wavesurfer
    alignments = [
        {
            "start": float(r["start"]),
            "end": float(r["end"]),
            "content": r["label"],
        }
        for r in current_regions
    ]

    # Note: The Python wavesurfer library doesn't support playback speed in the same way
    # The speed_selector is provided for UI consistency but may not affect playback
    speed_note = mo.callout(
        f"ℹ️ Current speed setting: **{speed_selector.value}x** (Note: Python wavesurfer may not support runtime speed control)",
        kind="info",
    )

    # Display the waveform with alignments
    # The play() function from wavesurfer library will render the audio with regions
    try:
        _ = play(final_audio_path, alignments=alignments)
        display_result = mo.vstack([speed_note])
    except Exception as e:
        display_result = mo.callout(
            f"❌ Error displaying waveform: {str(e)}", kind="danger"
        )

    display_result
    return (alignments,)


