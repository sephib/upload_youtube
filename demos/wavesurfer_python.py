    mo.md(f"""
    ### 📈 Statistics

    - **Total Regions**: {total_regions}
    - **Total Coverage**: {total_duration:.2f} seconds
    - **Average Region Duration**: {total_duration / total_regions:.2f} seconds
    """)
    return


